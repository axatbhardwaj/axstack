#!/usr/bin/env bun
// Read only the index. No hooks, configuration writes or working-tree reads.
import { readFileSync } from 'node:fs';

const ignoredPath = /(^|\/)(?:[^/]*\.lockb?|package-lock\.json|pnpm-lock\.yaml|yarn\.lock|go\.sum)$|(^|\/)(?:dist|build|__mocks__|__fixtures__|fixtures|captures)\/|\.(?:min|generated|gen)\.|\.(?:map|snap)$/i;
const asset = /\.(?:svg|png|jpe?g|gif|webp|avif|ico|bmp|tiff?|pdf|woff2?|ttf|otf|eot|mp[34]|wav|ogg|flac|webm|mov|avi|zip|gz|bz2|xz|7z|rar|tar|exe|dll|so|dylib|wasm|bin|class|jar|pyc|sqlite3?|db)$/i;
let root = process.cwd();
function git(...args) {
  const result = Bun.spawnSync(['git', '--literal-pathspecs', ...args], { cwd: root });
  if (result.exitCode !== 0) throw Error(result.stderr.toString().trim());
  return result.stdout.toString();
}

try {
  root = git('rev-parse', '--show-toplevel').trim();
  const gitDir = git('rev-parse', '--absolute-git-dir').trim();
  let ignores = [];
  try {
    ignores = readFileSync(`${gitDir}/info/token-limit-ignore`, 'utf8').split(/\r?\n/)
      .map((line) => line.trim()).filter((line) => line && !line.startsWith('#'))
      .map((pattern) => new Bun.Glob(pattern));
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  const paths = git('diff', '--cached', '--name-only', '--diff-filter=ACMR', '-z').split('\0').filter(Boolean);
  const offenders = [];
  for (const path of paths) {
    if (ignoredPath.test(path) || asset.test(path) || ignores.some((glob) => glob.match(path))) continue;
    if (git('ls-files', '--stage', '-z', '--', path).startsWith('160000 ')) continue;
    const bytes = Number(git('cat-file', '-s', `:${path}`));
    if (bytes <= 20000) continue;
    if (git('diff', '--cached', '--numstat', '--no-renames', '-z', '--', path).startsWith('-\t')) continue;
    // Consume the blob fully: closing a pipeline at line five can cause SIGPIPE.
    const firstLines = git('cat-file', 'blob', `:${path}`).split('\n', 5).join('\n');
    if (/@generated|auto[- ]?generated|do not edit|code generated by/i.test(firstLines)) continue;
    offenders.push(`${JSON.stringify(path)}: ${Math.floor(bytes / 4)} tokens`);
  }
  if (offenders.length) {
    console.error(`Staged files exceed 5000 tokens (20000 bytes; tokens = floor(bytes / 4)):
${offenders.join('\n')}

Split each file before committing:
1. Find seams: group top-level units by responsibility.
2. Create a folder named after the original file, with one module per responsibility.
   TS: foo.ts -> foo/types.ts, foo/parse.ts, foo/index.ts.
   Rust: foo.rs -> foo/mod.rs + submodules with re-exports.
   Svelte: child components + a .ts module for pure logic.
   Specs: one spec per describe block or behaviour.
   HTML docs: one doc per topic, linked from an index.
3. Keep the public surface stable via re-exports, or update all imports in the same commit.
4. Move code verbatim first, then refactor in a separate commit.
5. Aim for ~3000 tokens per file.
6. Stage the new files and re-commit.
If truly generated or recorded data, add a glob to .git/info/token-limit-ignore
or give the file a generated banner in its first 5 lines.`);
    process.exit(1);
  }
} catch (error) {
  console.error(`Staged-file token check failed: ${error.message}`);
  process.exit(1);
}
